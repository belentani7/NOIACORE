export function getCorpusStats() {
  const byCategory: Record<string, number> = {};
  const byRecommendation: Record<string, number> = {};
  const byRisk: Record<string, number> = {};

  OSS_100_BENCHMARK_CORPUS.forEach((repo) => {
    byCategory[repo.category] = (byCategory[repo.category] || 0) + 1;
    byRecommendation[repo.recommendation] = (byRecommendation[repo.recommendation] || 0) + 1;
    byRisk[repo.licenseRisk] = (byRisk[repo.licenseRisk] || 0) + 1;
  });

  return {
    totalCataloged: OSS_100_BENCHMARK_CORPUS.length,
    byCategory,
    byRecommendation,
    byRisk,
  };
}
